#!/usr/bin/env node
/** Validate both public worksheet exports, then atomically replace only the
 * generated X catalog. --snapshot accepts {masterRows,titleRows}; --check and
 * --dry-run print the validated identity diff without changing the catalog.
 */
import { existsSync } from "node:fs";
import { open, readFile, rename, stat, unlink } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildXCatalog, parseCsv } from "../feeds/x-source.mjs";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET_FILE = join(REPO_ROOT, "app/lib/x-broadcasts.ts");
const GENERATED_BEGIN = "// ---- GENERATED by `npm run broadcasts:sync` — do not hand-edit ----";
const GENERATED_END = "// ---- END GENERATED ----";
const MAX_TAB_BYTES = 4 * 1024 * 1024;
const SHEET_ID = process.env.CLIP_LIBRARY_SHEET_ID ?? "17uhDO06vmVEz96YrUnA6aHyV5fL_3AAs3ylOjrYRLwI";

/** @param {string} gid */
async function readTab(gid) {
  if (!/^[A-Za-z0-9_-]+$/.test(SHEET_ID)) throw new Error("Invalid worksheet identity");
  const response = await fetch(`https://docs.google.com/spreadsheets/d/${SHEET_ID}/export?format=csv&gid=${gid}`, { signal: AbortSignal.timeout(20000) });
  if (!response.ok || !response.body) throw new Error(`Worksheet ${gid} read failed (${response.status})`);
  if (Number(response.headers.get("content-length")) > MAX_TAB_BYTES) throw new Error(`Worksheet ${gid} exceeds 4 MB`);
  const reader = response.body.getReader();
  const chunks = [];
  let size = 0;
  try {
    while (true) {
      const { value, done } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > MAX_TAB_BYTES) throw new Error(`Worksheet ${gid} exceeds 4 MB`);
      chunks.push(value);
    }
  } finally { await reader.cancel(); }
  const bytes = new Uint8Array(size);
  let offset = 0;
  for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.byteLength; }
  return parseCsv(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
}

/** Decode only the established generated literal format, without evaluating
 * repository source. Reject unknown syntax instead of dropping baseline rows.
 * @param {string} source
 */
function baselineFrom(source) {
  const array = source.match(/export const xBroadcasts:\s*XBroadcast\[\]\s*=\s*\[([\s\S]*?)\];(?=[ \t]*(?:\r?\n|$))/);
  if (!array) throw new Error("Could not locate baseline xBroadcasts array");
  const string = '"(?:\\\\.|[^"\\\\])*"';
  const entry = new RegExp(`\\{\\s*id:\\s*(${string}),\\s*title:\\s*(${string}),\\s*poster:\\s*(${string}),\\s*date:\\s*(${string}),\\s*sourceUrl:\\s*(${string}|null)\\s*\\}`, "g");
  const baseline = [...array[1].matchAll(entry)].map(match => ({ id: JSON.parse(match[1]), title: JSON.parse(match[2]), poster: JSON.parse(match[3]), date: JSON.parse(match[4]), sourceUrl: JSON.parse(match[5]) }));
  if (array[1].replace(entry, "").replace(/[\s,]/g, "")) throw new Error("Unrecognized baseline entry syntax");
  return baseline;
}

/** @param {string} source @param {string} generated */
function replaceGenerated(source, generated) {
  const begin = source.indexOf(GENERATED_BEGIN);
  const end = source.indexOf(GENERATED_END);
  if (begin !== -1 || end !== -1) {
    if (begin === -1 || end < begin || source.indexOf(GENERATED_BEGIN, begin + 1) !== -1 || source.indexOf(GENERATED_END, end + 1) !== -1) throw new Error("Invalid or duplicated GENERATED markers");
    return source.slice(0, begin) + generated + source.slice(end + GENERATED_END.length);
  }
  return source.replace(/export const xBroadcasts:\s*XBroadcast\[\]\s*=\s*\[[\s\S]*?\];(?=[ \t]*(?:\r?\n|$))/, generated);
}

async function main() {
  const args = process.argv.slice(2);
  let snapshotPath;
  let check = false;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === "--snapshot" && args[index + 1] && !args[index + 1].startsWith("--") && !snapshotPath) snapshotPath = args[++index];
    else if (["--check", "--dry-run"].includes(args[index])) check = true;
    else throw new Error(`Unknown or incomplete argument ${args[index]}`);
  }
  let snapshot;
  if (snapshotPath) {
    if ((await stat(snapshotPath)).size > MAX_TAB_BYTES * 2) throw new Error("Snapshot exceeds 8 MB");
    snapshot = JSON.parse(await readFile(snapshotPath, "utf8"));
  } else {
    const [masterRows, titleRows] = await Promise.all([readTab("672400447"), readTab("1718293388")]);
    snapshot = { masterRows, titleRows };
  }
  const lockPath = `${TARGET_FILE}.sync.lock`;
  const lock = check ? null : await open(lockPath, "wx");
  let temporary;
  try {
    const original = await readFile(TARGET_FILE, "utf8");
    const baseline = baselineFrom(original);
    const result = buildXCatalog(snapshot.masterRows, snapshot.titleRows, baseline);
    // Existing accepted art remains stable. New episodes may use local artwork.
    for (const item of result.items.filter(item => result.diff.added.includes(item.id))) {
      for (const extension of ["png", "jpg"]) {
        if (existsSync(join(REPO_ROOT, "public/broadcasts", `${item.id}.${extension}`))) { item.poster = `/broadcasts/${item.id}.${extension}`; break; }
      }
    }
    const lines = result.items.map(item => `  { id: ${JSON.stringify(item.id)}, title: ${JSON.stringify(item.title)}, poster: ${JSON.stringify(item.poster)}, date: ${JSON.stringify(item.date)}, sourceUrl: ${JSON.stringify(item.sourceUrl)} },`);
    if (lines.some(line => line.includes(GENERATED_BEGIN) || line.includes(GENERATED_END))) throw new Error("Entry contains generated-region marker text");
    const generated = [GENERATED_BEGIN, "export const xBroadcasts: XBroadcast[] = [", ...lines, "];", GENERATED_END].join("\n");
    const candidate = replaceGenerated(original, generated);
    console.log(JSON.stringify({ count: result.items.length, diff: result.diff, check, changed: candidate !== original }, null, 2));
    if (check || candidate === original) return;
    temporary = `${TARGET_FILE}.${process.pid}.${crypto.randomUUID()}.tmp`;
    const output = await open(temporary, "wx", (await stat(TARGET_FILE)).mode);
    try { await output.writeFile(candidate, "utf8"); await output.sync(); }
    finally { await output.close(); }
    if (await readFile(TARGET_FILE, "utf8") !== original) throw new Error("Catalog changed during sync, retry required");
    await rename(temporary, TARGET_FILE);
    temporary = undefined;
  } finally {
    if (temporary) await unlink(temporary);
    if (lock) { await lock.close(); await unlink(lockPath); }
  }
}

main().catch(error => { console.error(`broadcasts:sync aborted: ${error.message}`); process.exitCode = 1; });
